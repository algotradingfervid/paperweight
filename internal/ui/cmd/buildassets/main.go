// Command buildassets writes internal/ui/static/ and assets_gen.go (run by
// go generate in internal/ui, CD-45).
package main

import (
	"fmt"
	"go/format"
	"log"
	"os"
	"path/filepath"
	"sort"
	"strings"

	"github.com/vardhan/internaltools/internal/ui/cmd/buildassets/build"
)

// consts maps each assets_gen.go constant to its file's base name and extension.
var consts = []struct{ name, base, ext string }{
	{"CSSURL", "app", "css"},
	{"JSURL", "app", "js"},
	{"InterURL", "inter-var-sub", "woff2"},
	{"NotoURL", "noto-sans-devanagari-sub", "woff2"},
}

func main() {
	files, err := build.BuildAssets(".")
	if err != nil {
		log.Fatal(err)
	}
	if err := os.RemoveAll("static"); err != nil {
		log.Fatal(err)
	}
	if err := os.MkdirAll("static", 0o750); err != nil {
		log.Fatal(err)
	}
	var names []string
	for name, b := range files {
		names = append(names, name)
		if err := os.WriteFile(filepath.Join("static", name), b, 0o600); err != nil {
			log.Fatal(err)
		}
	}
	sort.Strings(names)

	var src strings.Builder
	src.WriteString("// Code generated by cmd/buildassets; DO NOT EDIT.\n\npackage ui\n\n// Hashed URLs of the files in static/, served by Static() at " + build.URLPrefix + ".\nconst (\n")
	for _, c := range consts {
		found := ""
		for _, n := range names {
			if strings.HasPrefix(n, c.base+".") && strings.HasSuffix(n, "."+c.ext) && strings.Count(n, ".") == 2 {
				found = n
			}
		}
		if found == "" {
			log.Fatalf("no %s.*.%s built", c.base, c.ext)
		}
		fmt.Fprintf(&src, "\t%s = %q\n", c.name, build.URLPrefix+found)
	}
	src.WriteString(")\n")
	out, err := format.Source([]byte(src.String()))
	if err != nil {
		log.Fatal(err)
	}
	if err := os.WriteFile("assets_gen.go", out, 0o600); err != nil {
		log.Fatal(err)
	}
}
