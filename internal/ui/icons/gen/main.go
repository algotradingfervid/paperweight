// Command gen writes icons_gen.go from icons.txt and the vendored Lucide SVGs
// in lucide/ (run by go generate in internal/ui/icons). With -stdout it
// writes the source to standard output instead.
package main

import (
	"bytes"
	"encoding/xml"
	"fmt"
	"go/format"
	"io"
	"log"
	"os"
	"path/filepath"
	"strings"
)

// heavy lists the stroke exceptions of UI v2 §5.1: each glyph also renders
// as "<name>-heavy" at this width. The check inside a done step dot and the
// plus of the bottom-nav New button draw at 2.5; the state glyphs shown at
// 14 px draw at 2. Every other icon draws at 1.5.
var heavy = map[string]string{
	"check":         "2.5",
	"plus":          "2.5",
	"circle-dashed": "2",
	"clock":         "2",
	"circle-check":  "2",
	"circle-x":      "2",
	"ban":           "2",
	"circle-stop":   "2",
}

func main() {
	list, err := os.ReadFile("icons.txt")
	if err != nil {
		log.Fatal(err)
	}
	names := strings.Fields(string(list))
	licence := ""
	var b bytes.Buffer
	b.WriteString("// Code generated by icons/gen from icons.txt and lucide/*.svg; DO NOT EDIT.\n\n")
	body := new(bytes.Buffer)
	body.WriteString("var names = []string{\n")
	for _, n := range names {
		fmt.Fprintf(body, "%q,\n", n)
	}
	body.WriteString("}\n\nvar inner = map[string]string{\n")
	for _, n := range names {
		header, markup, err := parse(filepath.Join("lucide", n+".svg"))
		if err != nil {
			log.Fatalf("%s: %v", n, err)
		}
		if licence == "" {
			licence = header
		} else if header != licence {
			log.Fatalf("%s: licence header %q differs from %q", n, header, licence)
		}
		fmt.Fprintf(body, "%q: %q,\n", n, markup)
	}
	body.WriteString("}\n\nvar heavy = map[string]string{\n")
	for _, n := range names {
		if w, ok := heavy[n]; ok {
			fmt.Fprintf(body, "%q: %q,\n", n+"-heavy", w)
			delete(heavy, n)
		}
	}
	body.WriteString("}\n")
	if len(heavy) > 0 {
		log.Fatalf("heavy lists icons not in icons.txt: %v", heavy)
	}
	fmt.Fprintf(&b, "// %s\n// See lucide/LICENSE.\n\npackage icons\n\n", licence)
	b.WriteString(`import (
	"context"
	"io"
	"strings"

	"github.com/a-h/templ"
)

const open = ` + "`" + `<svg class="icon" aria-hidden="true" focusable="false" width="24" height="24" viewBox="0 0 24 24" fill="none" stroke="currentColor" stroke-width="` + "`" + `

const openEnd = ` + "`" + `" stroke-linecap="round" stroke-linejoin="round">` + "`" + `

// Icon renders the named Lucide icon as an inline, hidden-from-assistive-tech
// SVG at stroke 1.5; "<name>-heavy" renders a listed exception heavier. An
// unknown name panics at render.
func Icon(name string) templ.Component {
	return templ.ComponentFunc(func(ctx context.Context, w io.Writer) error {
		width, ok := heavy[name]
		if ok {
			name = strings.TrimSuffix(name, "-heavy")
		} else {
			width = "1.5"
		}
		markup, ok := inner[name]
		if !ok {
			panic("icons: unknown icon " + name)
		}
		return templ.Raw(open+width+openEnd+markup+"</svg>").Render(ctx, w)
	})
}

`)
	b.Write(body.Bytes())
	src, err := format.Source(b.Bytes())
	if err != nil {
		log.Fatal(err)
	}
	if len(os.Args) > 1 && os.Args[1] == "-stdout" {
		_, err = os.Stdout.Write(src)
	} else {
		err = os.WriteFile("icons_gen.go", src, 0o600)
	}
	if err != nil {
		log.Fatal(err)
	}
}

// parse returns the SVG's leading comment and the markup of the root svg's
// child elements.
func parse(path string) (header, markup string, err error) {
	f, err := os.Open(path) //nolint:gosec // path is built from icons.txt in this repo
	if err != nil {
		return "", "", err
	}
	defer func() { _ = f.Close() }()
	d := xml.NewDecoder(f)
	var m strings.Builder
	depth := 0
	for {
		tok, err := d.Token()
		if err == io.EOF {
			break
		}
		if err != nil {
			return "", "", err
		}
		switch t := tok.(type) {
		case xml.Comment:
			if depth == 0 && header == "" {
				header = strings.TrimSpace(string(t))
			}
		case xml.StartElement:
			depth++
			if depth == 1 {
				continue
			}
			m.WriteString("<" + t.Name.Local)
			for _, a := range t.Attr {
				var v bytes.Buffer
				if err := xml.EscapeText(&v, []byte(a.Value)); err != nil {
					return "", "", err
				}
				fmt.Fprintf(&m, " %s=\"%s\"", a.Name.Local, v.String())
			}
			m.WriteString(">")
		case xml.EndElement:
			if depth > 1 {
				m.WriteString("</" + t.Name.Local + ">")
			}
			depth--
		}
	}
	if header == "" {
		return "", "", fmt.Errorf("no licence comment")
	}
	return header, m.String(), nil
}
