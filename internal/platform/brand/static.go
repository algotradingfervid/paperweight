package brand

import (
	"bytes"
	"crypto/sha256"
	"encoding/hex"
	"fmt"
	"go/format"
	"io/fs"
	"mime"
	"net/http"
	"path"
	"strings"
	"sync"
)

// hashedName turns "logo.svg" into "logo.<sha256[:8]>.svg".
func hashedName(name string, data []byte) string {
	sum := sha256.Sum256(data)
	ext := path.Ext(name)
	return strings.TrimSuffix(name, ext) + "." + hex.EncodeToString(sum[:])[:8] + ext
}

// Generate returns the source of brand_gen.go for c and the files it names. It is used by
// go generate (./gen) and by the test that checks the committed file is up to date.
func Generate(c Config, files fs.FS) ([]byte, error) {
	var b bytes.Buffer
	b.WriteString("// Code generated by go run ./gen; DO NOT EDIT.\n\npackage brand\n\nconst (\n")
	for _, s := range c.slots() {
		w, h, err := measure(files, s)
		if err != nil {
			return nil, err
		}
		data, err := fs.ReadFile(files, s.name)
		if err != nil {
			return nil, err
		}
		id := map[string]string{"app_logo": "AppLogo", "document_logo": "DocumentLogo", "favicon": "Favicon"}[s.key]
		fmt.Fprintf(&b, "%sURL = %q\n", id, "/static/brand/"+hashedName(s.name, data))
		if s.logo {
			fmt.Fprintf(&b, "%sWidth = %d\n%sHeight = %d\n", id, w, id, h)
		}
	}
	b.WriteString(")\n")
	return format.Source(b.Bytes())
}

type staticFile struct {
	data  []byte
	ctype string
}

var staticFiles = sync.OnceValue(func() map[string]staticFile {
	c := Load()
	m := map[string]staticFile{}
	for _, s := range c.slots() {
		data, err := fs.ReadFile(assets(), s.name)
		if err != nil {
			panic(err)
		}
		m[hashedName(s.name, data)] = staticFile{data: data, ctype: mime.TypeByExtension(path.Ext(s.name))}
	}
	return m
})

// Static serves the brand images under their content-hashed names (AppLogoURL,
// DocumentLogoURL, FaviconURL) with the immutable cache header; any other path is 404
// and any method but GET or HEAD is 405. WP3 mounts it at /static/brand/, with or
// without stripping that prefix.
func Static() http.Handler {
	files := staticFiles()
	return http.HandlerFunc(func(w http.ResponseWriter, r *http.Request) {
		if r.Method != http.MethodGet && r.Method != http.MethodHead {
			w.Header().Set("Allow", "GET, HEAD")
			http.Error(w, "Only GET and HEAD are allowed here.", http.StatusMethodNotAllowed)
			return
		}
		name := strings.TrimPrefix(strings.TrimPrefix(r.URL.Path, "/static/brand/"), "/")
		f, ok := files[name] // names have no "/", so any sub-path is not found
		if !ok {
			http.NotFound(w, r)
			return
		}
		w.Header().Set("Content-Type", f.ctype)
		w.Header().Set("X-Content-Type-Options", "nosniff")
		w.Header().Set("Cache-Control", "public, max-age=31536000, immutable")
		_, _ = w.Write(f.data)
	})
}
